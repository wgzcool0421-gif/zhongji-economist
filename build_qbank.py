# ========== GENERATE JS CODE ==========
def gen_qbank_js(questions, qbank_type='single'):
    """Generate JavaScript array entries for QBANK"""
    lines = []
    for q in questions:
        ch, question, options, answer, explanation = q
        
        # Escape single quotes in text
        question = question.replace("'", "\\'")
        explanation = explanation.replace("'", "\\'")
        options_escaped = [o.replace("'", "\\'") for o in options]
        
        if isinstance(answer, list):
            # Multi-choice
            ans_str = str(answer)
            lines.append(f"  {{ch:{ch},type:'multi',q:'{question}',o:{json.dumps(options_escaped, ensure_ascii=False)},a:{ans_str},x:'{explanation}'}},")
        else:
            # Single choice
            lines.append(f"  {{ch:{ch},q:'{question}',o:{json.dumps(options_escaped, ensure_ascii=False)},a:{answer},x:'{explanation}'}},")
    
    return '\n'.join(lines)

