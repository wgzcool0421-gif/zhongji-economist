# Read existing ECON_QBANK and IP_QBANK from index.html
def extract_existing_qs(filepath, qbank_var):
    """Extract question texts from existing QBANK in index.html"""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Find the array
    start = content.find(f'const {qbank_var} = [')
    if start == -1:
        return set()
    end = content.find('];', start)
    array_text = content[start:end+2]
    
    # Extract question texts
    q_texts = set()
    # Match q:'...'
    for m in re.finditer(r"q:'([^']+)'", array_text):
        q_texts.add(m.group(1))
    
    return q_texts

def dedup_questions(new_questions, existing_qs):
    """Remove questions that already exist"""
    unique = []
    for q in new_questions:
        q_text = q[1]  # question text
        if q_text not in existing_qs:
            unique.append(q)
    return unique

